CREATE TABLE IF NOT EXISTS users (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(100) NOT NULL UNIQUE, email VARCHAR(150) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, full_name VARCHAR(150) NOT NULL, avatar_url VARCHAR(500), role_id BIGINT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_users_role FOREIGN KEY(role_id) REFERENCES roles(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS categories (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE, slug VARCHAR(100) NOT NULL UNIQUE, description TEXT
);

CREATE TABLE IF NOT EXISTS articles (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(255) NOT NULL, slug VARCHAR(255) NOT NULL UNIQUE, summary TEXT, content LONGTEXT NOT NULL,
 featured_image VARCHAR(500), category_id BIGINT NOT NULL, author_id BIGINT NOT NULL, is_breaking BOOLEAN DEFAULT FALSE, is_top_news BOOLEAN DEFAULT FALSE,
 views_count BIGINT DEFAULT 0, reading_time INT DEFAULT 3, meta_title VARCHAR(255), meta_description TEXT, status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
 published_at TIMESTAMP NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_articles_category FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE RESTRICT,
 CONSTRAINT fk_articles_author FOREIGN KEY(author_id) REFERENCES users(id) ON DELETE RESTRICT,
 INDEX idx_articles_status_published(status,published_at), INDEX idx_articles_category(category_id,status)
);

CREATE TABLE IF NOT EXISTS discussions (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, author_name VARCHAR(100) NOT NULL, author_avatar VARCHAR(500), author_handle VARCHAR(100),
 title VARCHAR(255) NOT NULL, content TEXT NOT NULL, likes_count INT DEFAULT 0, comments_count INT DEFAULT 0, is_trending BOOLEAN DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, discussion_id BIGINT NOT NULL, author_name VARCHAR(100) NOT NULL, author_avatar VARCHAR(500), content TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_comments_discussion FOREIGN KEY(discussion_id) REFERENCES discussions(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS polls (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, question VARCHAR(255) NOT NULL, total_votes BIGINT DEFAULT 0, is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS poll_options (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, poll_id BIGINT NOT NULL, option_text VARCHAR(150) NOT NULL, votes_count BIGINT DEFAULT 0,
 CONSTRAINT fk_poll_options_poll FOREIGN KEY(poll_id) REFERENCES polls(id) ON DELETE CASCADE, INDEX idx_poll_options_poll(poll_id)
);
